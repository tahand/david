<#
.SYNOPSIS
  Sets up and runs the whole clinic system in Docker for local testing on Windows.

.DESCRIPTION
  Wraps docker-compose.local.yml. On first start it generates .env.docker with
  random secrets, builds the images, applies migrations, seeds demo data and
  waits until the app answers on http://localhost:8080.

  Requires Docker Desktop (WSL 2 backend). Works in Windows PowerShell 5.1 and
  PowerShell 7. Run it through local.cmd in the repo root to avoid execution
  policy prompts.

.EXAMPLE
  .\local.cmd start            # set up (first time) and start everything
  .\local.cmd start -NoSeed    # start without (re)seeding demo data
  .\local.cmd logs api         # follow one service's logs
  .\local.cmd admin admin@example.test
  .\local.cmd reset            # delete all local data and secrets
#>
[CmdletBinding()]
param(
  [Parameter(Position = 0)]
  [ValidateSet('start', 'stop', 'restart', 'reset', 'logs', 'status', 'admin', 'psql', 'help')]
  [string]$Command = 'start',

  [Parameter(Position = 1)]
  [string]$Target,

  [switch]$NoSeed,
  [switch]$Force
)

$Root = Split-Path -Parent $PSScriptRoot
$ComposeFile = Join-Path $Root 'docker-compose.local.yml'
$EnvFile = Join-Path $Root '.env.docker'
$Volume = 'clinic-local_pgdata'
$AppUrl = 'http://localhost:8080'
$MailUrl = 'http://localhost:8026'
$SeedPassword = 'demo-password-not-for-production'

function Write-Step([string]$Message) { Write-Host "==> $Message" -ForegroundColor Cyan }
function Write-Warn([string]$Message) { Write-Host "WARNING: $Message" -ForegroundColor Yellow }
function Stop-WithError([string]$Message) {
  Write-Host "ERROR: $Message" -ForegroundColor Red
  exit 1
}

# Native commands report failure through $LASTEXITCODE, not exceptions.
function Invoke-Compose {
  & docker compose -f $ComposeFile @args
  if ($LASTEXITCODE -ne 0) {
    Stop-WithError "'docker compose $($args -join ' ')' failed (exit code $LASTEXITCODE)."
  }
}

function Test-Docker {
  if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Stop-WithError 'Docker is not installed. Install Docker Desktop: https://www.docker.com/products/docker-desktop/'
  }
  $null = & docker info --format '{{.ServerVersion}}' 2>&1
  if ($LASTEXITCODE -ne 0) {
    Stop-WithError 'Docker Desktop is not running. Start it, wait until it says "Engine running", then try again.'
  }
  $null = & docker compose version 2>&1
  if ($LASTEXITCODE -ne 0) {
    Stop-WithError 'Docker Compose v2 is required. Update Docker Desktop.'
  }
}

function New-Secret([int]$Bytes) {
  $buffer = New-Object byte[] $Bytes
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
  return [Convert]::ToBase64String($buffer)
}

function Test-DataVolume {
  $found = & docker volume ls --quiet --filter "name=^$Volume$" 2>$null
  return [bool]$found
}

# Secrets for the local stack. Written without a BOM: Docker would otherwise
# read the first variable name with a stray character in front of it.
function Initialize-EnvFile {
  if (Test-Path $EnvFile) { return }
  if (Test-DataVolume) {
    Write-Warn ".env.docker is missing but local data exists. Data encrypted with the old key can't be read; run '.\local.cmd reset' if pages fail to load."
  }
  Write-Step 'Generating .env.docker with new random secrets'
  $lines = @(
    '# Generated by scripts/local.ps1 for docker-compose.local.yml. Local testing only.',
    '# Deleting this file makes existing encrypted data unreadable; use "local.cmd reset".',
    "SESSION_SECRET=$(New-Secret 64)",
    "DATA_ENCRYPTION_KEY=$(New-Secret 32)",
    'DATA_ENCRYPTION_KEY_VERSION=1',
    '# Breached-password check (fails open when offline).',
    'HIBP_CHECK_ENABLED=true'
  )
  $utf8NoBom = New-Object System.Text.UTF8Encoding $false
  [System.IO.File]::WriteAllText($EnvFile, (($lines -join "`n") + "`n"), $utf8NoBom)
}

function Wait-ForApp([int]$TimeoutSeconds = 180) {
  Write-Step "Waiting for $AppUrl"
  $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
  while ((Get-Date) -lt $deadline) {
    try {
      $res = Invoke-WebRequest -Uri "$AppUrl/api/health" -UseBasicParsing -TimeoutSec 5
      if ($res.StatusCode -eq 200) { return }
    } catch {
      Start-Sleep -Seconds 2
    }
  }
  Stop-WithError "The app did not become ready within $TimeoutSeconds seconds. Check '.\local.cmd logs api'."
}

function Show-Info {
  Write-Host ''
  Write-Host 'Clinic is running.' -ForegroundColor Green
  Write-Host "  App:            $AppUrl   (use 'localhost', not 127.0.0.1)"
  Write-Host "  Emails:         $MailUrl  (all outgoing mail is caught here)"
  Write-Host ''
  Write-Host "  Demo logins (password: $SeedPassword)"
  Write-Host '    Patient:      test.patient@example.test'
  Write-Host '    Receptionist: reception@example.test   (sets up two-step verification on first sign-in)'
  Write-Host '    Doctor:       dr.example@example.test  (sets up two-step verification on first sign-in)'
  Write-Host '    Admin:        create one with  .\local.cmd admin you@example.test'
  Write-Host ''
  Write-Host '  Phone testing: open the app in Chrome/Edge DevTools device mode (Ctrl+Shift+M).'
  Write-Host '  Stop: .\local.cmd stop    Logs: .\local.cmd logs [api|web|migrate]    Wipe data: .\local.cmd reset'
}

function Start-Stack {
  Test-Docker
  Initialize-EnvFile
  if ($NoSeed) { $env:SEED_DEMO_DATA = 'false' } else { $env:SEED_DEMO_DATA = 'true' }
  Write-Step 'Building images and starting containers (the first run takes a few minutes)'
  & docker compose -f $ComposeFile up --detach --build
  if ($LASTEXITCODE -ne 0) {
    Write-Host ''
    Write-Host 'Recent migration/seed output:' -ForegroundColor Yellow
    & docker compose -f $ComposeFile logs --tail 40 migrate
    Stop-WithError "Start-up failed. See the output above, or run '.\local.cmd logs'."
  }
  Wait-ForApp
  Show-Info
}

Push-Location $Root
try {
  switch ($Command) {
    'start' { Start-Stack }
    'restart' {
      Test-Docker
      Invoke-Compose down
      Start-Stack
    }
    'stop' {
      Test-Docker
      Write-Step 'Stopping containers (data is kept)'
      Invoke-Compose down
    }
    'reset' {
      Test-Docker
      if (-not $Force) {
        $answer = Read-Host 'This deletes the local database, demo data and secrets. Type "reset" to continue'
        if ($answer -ne 'reset') { Write-Host 'Cancelled.'; exit 0 }
      }
      Write-Step 'Removing containers, data volume and .env.docker'
      Invoke-Compose down --volumes --remove-orphans
      if (Test-Path $EnvFile) { Remove-Item $EnvFile -Force }
      Write-Host "Done. Run '.\local.cmd start' for a fresh system."
    }
    'logs' {
      Test-Docker
      if ($Target) { Invoke-Compose logs --follow --tail 200 $Target }
      else { Invoke-Compose logs --follow --tail 200 }
    }
    'status' {
      Test-Docker
      Invoke-Compose ps --all
    }
    'admin' {
      Test-Docker
      $email = $Target
      if (-not $email) { $email = Read-Host 'Admin email address' }
      Write-Step "Creating admin $email (you'll be asked for a password, 12+ characters)"
      Invoke-Compose run --rm --no-deps -it api npm run create-admin -- --email $email
    }
    'psql' {
      Test-Docker
      Invoke-Compose exec postgres psql -U postgres -d clinic
    }
    'help' { Get-Help $PSCommandPath -Detailed }
  }
} finally {
  Pop-Location
}
